#!/usr/bin/env python3
"""Build supplementary Cyber Blue SVGs into transparent PNGs and flash A8.

Build-only dependencies: CairoSVG 2.8.2 and Pillow 13.0.0. Firmware needs no
SVG/PNG decoder. Existing imported pack and the legacy atlas are untouched.
Only mask variants referenced by the Cyber mapper enter the C translation unit.
"""
from pathlib import Path
import hashlib
import io
import json
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / ".test-deps/svg-runtime"))
import cairosvg
from PIL import Image

folder = ROOT / "assets/cyber-icons"
target = ROOT / "components/dsr_ui/cyber_icons"
mapping = (target.parent / "dsr_ui_cyber_icons.c").read_text()
used = set(re.findall(r"&(shudx_\w+_(?:24|32|48))\b", mapping))
assert used, "Register the supplementary icons before building"
blocks, records, sources = [], {}, {}
for svg in sorted((folder / "svg").glob("*.svg")):
    data = svg.read_bytes()
    sources[svg.stem] = hashlib.sha256(data).hexdigest()
    # Supersample once, with transparent interiors and a common 1.9 px stroke.
    rgba = Image.open(io.BytesIO(cairosvg.svg2png(bytestring=data, output_width=384, output_height=384)))
    alpha = rgba.getchannel("A")
    for n in (24, 32, 48):
        mask = alpha.resize((n, n), Image.Resampling.LANCZOS)
        png = Image.new("RGBA", (n, n), (0, 207, 255, 0))
        png.putalpha(mask)
        path = folder / "png" / str(n) / (svg.stem + ".png")
        path.parent.mkdir(parents=True, exist_ok=True)
        buffer = io.BytesIO(); png.save(buffer, format="PNG", optimize=True)
        path.write_bytes(buffer.getvalue())
        symbol = f'shudx_{svg.stem.replace("-", "_")}_{n}'
        if symbol not in used:
            continue
        raw = mask.tobytes()
        assert len(raw) == n * n and 0 in raw and max(raw) > 200
        values = [", ".join(f"0x{b:02x}" for b in raw[i:i+16]) for i in range(0, len(raw), 16)]
        blocks.append(f"static const uint8_t {symbol}_px[{len(raw)}] = {{\n " + ",\n ".join(values) + "\n};\n" +
                      f"const lv_image_dsc_t {symbol} = {{\n" +
                      f" .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {n}, .h = {n}, .stride = {n}}},\n" +
                      f" .data_size = {len(raw)}, .data = {symbol}_px\n}};")
        records[symbol] = {"size": n, "bytes": len(raw), "sha256": hashlib.sha256(raw).hexdigest(), "svg": svg.name}
assert used == set(records)
(target / "shelly_hud_extra.c").write_text('/* Generated by tools/build_cyber_extra_icons.py. Supplemental outline assets. */\n#include "shelly_hud_extra.h"\n\n' + "\n\n".join(blocks) + "\n")
(target / "shelly_hud_extra.h").write_text('#ifndef SHELLY_HUD_EXTRA_H\n#define SHELLY_HUD_EXTRA_H\n#include "lvgl.h"\n' + "".join(f"extern const lv_image_dsc_t {s};\n" for s in sorted(used)) + '#endif\n')
(target / "extra-manifest.json").write_text(json.dumps({
    "source": "assets/cyber-icons/svg (outline interpretation of supplied missing-icon references)",
    "generator": "CairoSVG 2.8.2; Pillow 13.0.0; 384 px supersampling; Lanczos",
    "format": "LV_COLOR_FORMAT_A8; transparent monochrome coverage; runtime recoloring",
    "svg_sha256": sources, "mask_bytes": sum(r["bytes"] for r in records.values()), "assets": records,
}, indent=2) + "\n")
print(f'Built {len(sources)} SVGs, {len(sources)*3} transparent PNGs, {len(records)} referenced A8 masks ({sum(r["bytes"] for r in records.values())} bytes in Flash)')
