#!/usr/bin/env python3
"""Build code-native, reference-inspired BLU outlines. No bitmap sheets are imported.
A8 lives in Flash; runtime recoloring; no PNG/SVG decoder or dynamic cache.
"""
import hashlib,io,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'.test-deps/svg-runtime'))
import cairosvg
from PIL import Image
FOLDER=ROOT/'assets/cyber-blu-icons'
TARGET=ROOT/'components/dsr_ui/cyber_icons'
# Frames, separate sashes, handles and diagonal glass marks follow the supplied
# reference; no glow pixels, labels, or colored background are baked into masks.
cap='<path d="M8 9h48v4H8z M6 53h52v5H6z"/>'
frame='<path d="M11 13v40 M53 13v40"/>'
closed='<rect x="15" y="17" width="15" height="32" rx="1"/><rect x="34" y="17" width="15" height="32" rx="1"/><path d="M15 33h15 M34 33h15 M28 29v6 M36 29v6"/>'
glass='<path opacity=".38" d="m18 27 8-7 m11 7 8-7 m-27 23 8-7 m11 7 8-7"/>'
window_closed='<path d="M10 8h44v48H10z M7 59h50"/><path d="M15 13h15v38H15z M34 13h15v38H34z M27 29v7 M37 29v7"/>'
# Both sashes project OUTSIDE the fixed opening, leaving its center visibly open.
window_open='<path d="M18 14h28v40H18z M13 58h38"/><path d="m18 16-14-9v49l14-5z M46 16l14-9v49l-14-5z M11 29v7 M53 29v7"/><path opacity=".4" d="m7 13 8 5v27l-8 5 M57 13l-8 5v27l8 5"/>'
window_tilted=cap+frame+'<path opacity=".45" d="M15 16h34v37H15z"/><path d="m10 23 40-4 3 34H15z M16 28l13-1 2 21H20z M34 27l12-1 2 22H36z M28 23l9-1"/>'
# Unknown is a frame plus explicit question badge, never a closed-state glyph alone.
badge='<circle cx="49" cy="47" r="11"/><path d="M45 43c0-6 9-6 9 0 0 3-5 3-5 6 M49 53h.1"/>'
door_frame='<path d="M12 57V7h39v50 M8 58h48"/>'
door_closed='<path d="M15 7h35v50 M11 59h43"/><path d="M21 13h23v43H21z M37 32h3"/>'
door_open='<path d="M21 10h30v47 M17 59h39"/><path d="m21 12-15-8v49l15 3z M11 29v7 M27 15h19v37"/>'
icons={'window-closed':window_closed,'window-open':window_open,'window-tilted':window_tilted,'window-no-data':'<path d="M8 9h48v4H8z M6 53h29v5H6z M11 13v40 M53 13v19 M16 18h14v32H16z M16 34h14 M34 18h14v13H34z"/>'+badge,'door-closed':door_closed,'door-open':door_open,'door-no-data':'<path d="M12 57V7h39v25 M8 58h27 M18 14h26v18 M18 14v41h17"/>'+badge,
'illuminance':'<circle cx="32" cy="32" r="12"/><path d="M32 6v7 M32 51v7 M6 32h7 M51 32h7 M13 13l5 5 M46 46l5 5 M13 51l5-5 M46 18l5-5"/>',
'signal':'<path stroke-width="6" d="M12 53V43 M25 53V33 M38 53V23 M51 53V11"/>',
'clock':'<circle cx="32" cy="32" r="24"/><path d="M32 17v16l12 7"/>'}
records={};blocks=[];sources={}
for name,body in icons.items():
    svg=('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" fill="none" stroke="white" stroke-width="2.6" stroke-linejoin="round" stroke-linecap="round">'+body+'</svg>\n').encode()
    path=FOLDER/'svg'/(name+'.svg');path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(svg)
    sources[name]=hashlib.sha256(svg).hexdigest()
    alpha=Image.open(io.BytesIO(cairosvg.svg2png(bytestring=svg,output_width=512,output_height=512))).getchannel('A')
    sizes=(24,32,48,80) if name.startswith(('window','door')) else (24,)
    for n in sizes:
        mask=alpha.resize((n,n),Image.Resampling.LANCZOS)
        png=Image.new('RGBA',(n,n),(0,207,255,0));png.putalpha(mask)
        path=FOLDER/'png'/str(n)/(name+'.png');path.parent.mkdir(parents=True,exist_ok=True);png.save(path,optimize=True)
        raw=mask.tobytes();symbol='shudb_'+name.replace('-','_')+'_'+str(n)
        values=[', '.join('0x%02x'%b for b in raw[i:i+16]) for i in range(0,len(raw),16)]
        blocks.append('static const uint8_t '+symbol+'_px['+str(len(raw))+'] = {\n '+',\n '.join(values)+'\n};\nconst lv_image_dsc_t '+symbol+' = {\n .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = '+str(n)+', .h = '+str(n)+', .stride = '+str(n)+'},\n .data_size = '+str(len(raw))+', .data = '+symbol+'_px\n};')
        records[symbol]=dict(size=n,bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest(),svg=name+'.svg')
(TARGET/'shelly_hud_blu.h').write_text('#ifndef SHELLY_HUD_BLU_H\n#define SHELLY_HUD_BLU_H\n#include "lvgl.h"\n'+''.join('extern const lv_image_dsc_t '+s+';\n' for s in sorted(records))+'#endif\n')
(TARGET/'shelly_hud_blu.c').write_text('/* Generated by tools/build_cyber_blu_icons.py; original reference-inspired outlines. */\n#include "shelly_hud_blu.h"\n'+ '\n'.join(blocks)+'\n')
(TARGET/'blu-manifest.json').write_text(json.dumps(dict(source='code-native outlines based on supplied Window / Door reference pack',format='LV_COLOR_FORMAT_A8; transparent runtime recoloring',svg_sha256=sources,mask_bytes=sum(r['bytes'] for r in records.values()),assets=records),indent=2)+'\n')
print('Built',len(records),'BLU A8 masks;',sum(r['bytes'] for r in records.values()),'Flash bytes')
