#!/usr/bin/env python3
"""Copy only referenced A8 declarations from the supplied CC0 icon ZIP.

No image resampling, tracing, SVG/PNG conversion or runtime dependency.
The original descriptor symbols and mask bytes are preserved exactly.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import zipfile

ROOT = Path(__file__).resolve().parents[1]
p = argparse.ArgumentParser()
p.add_argument("archive", type=Path)
args = p.parse_args()
target = ROOT / "components/dsr_ui/cyber_icons"
target.mkdir(exist_ok=True)
used = sorted(set(re.findall(r"&(?P<symbol>shud_\w+_(?:24|32|48))\b",
                            (target.parent / "dsr_ui_cyber_icons.c").read_text())))
prefix = "Shelly_HUD_Cyber_Blue_Icons/"
with zipfile.ZipFile(args.archive) as z:
    manifest = json.loads(z.read(prefix + "manifest.json"))
    declared = {s for i in manifest["icons"] for s in i["lvgl_symbols"]}
    assert set(used) <= declared
    sources = {n: z.read(prefix + f"lvgl9_a8/shelly_hud_icons_{n}.c").decode() for n in (24, 32, 48)}
    blocks = {}
    records = {}
    for symbol in used:
        size = int(symbol.rsplit("_", 1)[1])
        match = re.search(r"static const uint8_t " + symbol + r"_px\[.*?\n};\nconst lv_image_dsc_t " + symbol + r" = \{.*?\n};", sources[size], re.S)
        assert match, symbol
        block = match.group()
        data = bytes(int(h, 16) for h in re.findall(r"0x([0-9a-fA-F]{2})", block.split("};", 1)[0]))
        assert len(data) == size * size
        assert 0 in data and any(data)
        blocks[symbol] = block
        records[symbol] = {"size": size, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()}
    (target / "shelly_hud_icons.c").write_text(
        '/* Imported unchanged masks from Shelly HUD icon pack 1.0.0, CC0-1.0.\n'
        ' * Generated by tools/import_cyber_icons.py; only referenced variants. */\n'
        '#include "shelly_hud_icons.h"\n\n' + "\n\n".join(blocks.values()) + "\n")
    (target / "shelly_hud_icons.h").write_text(
        '#ifndef SHELLY_HUD_ICONS_H\n#define SHELLY_HUD_ICONS_H\n#include "lvgl.h"\n' +
        "".join(f"extern const lv_image_dsc_t {s};\n" for s in used) + '#endif\n')
    (target / "LICENSE.txt").write_bytes(z.read(prefix + "LICENSE.txt"))
    (target / "manifest.json").write_text(json.dumps({
        "source": args.archive.name, "version": manifest["version"], "license": "CC0-1.0",
        "archive_sha256": hashlib.sha256(args.archive.read_bytes()).hexdigest(),
        "format": "LV_COLOR_FORMAT_A8; original source arrays, no conversion",
        "mask_bytes": sum(r["bytes"] for r in records.values()), "assets": records,
    }, indent=2) + "\n")
print(f'Imported {len(used)} referenced masks ({sum(r["bytes"] for r in records.values())} bytes)')
