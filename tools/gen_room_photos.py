#!/usr/bin/env python3
"""Built-in room photos (owner artwork, 100x100) -> RGB565 assets + C table.

Byte order matches the Web Panel upload (little-endian RGB565). Each photo ID
is the first 16 bytes of SHA-256 over its pixels, the same rule as uploaded
photos, so configs keep one 32-hex-char photo field.

Default: verify the committed outputs. --write: regenerate them.
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/rooms'
ASSETS = ROOT / 'components/dsr_ui/brand'
TABLE = ROOT / 'components/dsr_ui/dsr_ui_room_photos.c'
# file stem, label shown in the gallery (PL; translated on the LCD)
ROOMS = [('wohnzimmer', 'Salon'), ('kueche', 'Kuchnia'), ('schlafzimmer', 'Sypialnia'), ('badezimmer', 'Łazienka'),
         ('vorraum', 'Przedpokój'), ('keller', 'Piwnica'), ('dachboden', 'Strych'), ('zaehlerkasten', 'Rozdzielnia')]
SIZE = 100


def pixels(path):
    from PIL import Image
    image = Image.open(path).convert('RGB')
    if image.size != (SIZE, SIZE):
        raise SystemExit(f'{path}: expected {SIZE}x{SIZE}, got {image.size}')
    raw, out = image.tobytes(), bytearray()
    for i in range(0, len(raw), 3):
        value = (raw[i] >> 3) << 11 | (raw[i + 1] >> 2) << 5 | (raw[i + 2] >> 3)
        out += bytes((value & 255, value >> 8))
    return bytes(out)


def render(entries):
    lines = ['/* Generated by tools/gen_room_photos.py from assets/rooms (owner artwork). Do not edit. */',
             '#include "dsr_ui_style.h"', '#include <string.h>', '']
    for stem, _, _ in entries:
        lines.append(f'extern const uint8_t _binary_room_{stem}_rgb565_start[];')
    lines += ['', 'static const dsr_room_photo_t photos[]={']
    for stem, label, digest in entries:
        lines.append(f' {{"{digest}","{label}",_binary_room_{stem}_rgb565_start}},')
    lines += ['};', 'unsigned dsr_room_photo_count(void){return sizeof(photos)/sizeof(photos[0]);}',
              'const dsr_room_photo_t *dsr_room_photo(unsigned index){return index<dsr_room_photo_count()?&photos[index]:NULL;}',
              'const dsr_room_photo_t *dsr_room_photo_find(const char *id)',
              '{if(!id||!id[0])return NULL;for(unsigned i=0;i<dsr_room_photo_count();i++)if(!strcmp(photos[i].id,id))return &photos[i];return NULL;}', '']
    return '\n'.join(lines)


def main():
    write = '--write' in sys.argv[1:]
    entries, problems = [], []
    try:
        import PIL  # noqa: F401  (CI may lack Pillow: then check committed assets only)
        decode = True
    except ImportError:
        decode = write or False
    for stem, label in ROOMS:
        asset = ASSETS / f'room_{stem}.rgb565'
        data = pixels(SOURCE / f'{stem}.png') if decode else asset.read_bytes()
        if len(data) != SIZE * SIZE * 2:
            problems.append(f'{asset.relative_to(ROOT)} has {len(data)} bytes')
        digest = hashlib.sha256(data).hexdigest()[:32]
        entries.append((stem, label, digest))
        if write:
            asset.write_bytes(data)
        elif not asset.exists() or asset.read_bytes() != data:
            problems.append(f'{asset.relative_to(ROOT)} is stale')
    table = render(entries)
    if write:
        TABLE.write_text(table)
    elif not TABLE.exists() or TABLE.read_text() != table:
        problems.append(f'{TABLE.relative_to(ROOT)} is stale')
    if problems:
        raise SystemExit('Room photos out of date (run tools/gen_room_photos.py --write):\n' + '\n'.join(problems))
    print(f'PASS: {len(entries)} built-in room photos {SIZE}x{SIZE} RGB565, content-addressed IDs match assets')


if __name__ == '__main__':
    main()
