#!/usr/bin/env python3
"""Convert Apache-2.0 Material Symbols Rounded SVGs to antialiased A8 masks.

No network or SVG parser is needed by firmware. Inputs and their hashes are
kept in third_party/material-symbols; output is a fixed 96 KiB Flash atlas.
Build dependency: cairosvg==2.8.2 and Pillow; when cairosvg is not
installed, headless Chromium (Playwright, used by the panel tests) renders the
same SVGs at 256 px. The 0.7.51 atlas was rendered with Chromium.
Run from any directory.
"""
from pathlib import Path
import hashlib
import io
import json
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.test-deps/svg-runtime'))
from PIL import Image
try:
    import cairosvg
except ImportError:
    cairosvg = None

ICONS = ['speed', 'home', 'bolt', 'settings', 'add', 'power_settings_new',
         'arrow_back_ios_new', 'edit', 'info', 'power', 'lightbulb', 'chair',
         'bed', 'kitchen', 'bathtub', 'wifi', 'grid_view', 'expand_more',
         'keyboard_arrow_up', 'keyboard_arrow_down', 'sensor_door', 'blinds',
         'battery_full', 'auto_awesome',
         # 0.7.51: selectable device icons (Shelly app "Standardbilder")
         'outlet', 'mode_fan', 'thermostat', 'tv', 'water_heater', 'garage_home',
         'door_front', 'floor_lamp', 'wall_lamp', 'ev_station', 'kettle',
         'coffee_maker', 'local_laundry_service', 'ac_unit', 'speaker', 'router']
COUNT = len(ICONS)
src = ROOT / 'third_party/material-symbols'
manifest = json.loads((src / 'sources.json').read_text())
parts = ['/* Generated by tools/build_ui_icons.py; Google Material Symbols Rounded, Apache-2.0. */',
         '#include "lvgl.h"', 'static const uint8_t masks[%d][4096] = {' % COUNT]
browser = None
def render(data):
    global browser
    if cairosvg:
        return cairosvg.svg2png(bytestring=data, output_width=256, output_height=256)
    import base64
    if browser is None:
        from playwright.sync_api import sync_playwright
        browser = sync_playwright().start().chromium.launch()
    page = browser.new_page(viewport={'width': 256, 'height': 256})
    page.set_content('<html><body style="margin:0;background:transparent"><img style="display:block" width=256 height=256 src="data:image/svg+xml;base64,'
                     + base64.b64encode(data).decode() + '"></body></html>')
    png = page.screenshot(omit_background=True)
    page.close()
    return png
for name in ICONS:
    data = (src / (name + '.svg')).read_bytes()
    assert hashlib.sha256(data).hexdigest() == manifest['sha256'][name]
    image = Image.open(io.BytesIO(render(data))).getchannel('A')
    # A common optical body, centered before filtering. Rounded curves retain
    # subpixel coverage at the smallest navigation/control sizes.
    image = image.crop(image.getbbox())
    image.thumbnail((216, 216), Image.Resampling.LANCZOS)
    canvas = Image.new('L', (256, 256))
    canvas.paste(image, ((256-image.width)//2, (256-image.height)//2))
    mask = canvas.resize((64,64), Image.Resampling.LANCZOS).tobytes()
    parts.append('/* ' + name + ' */ {' + ','.join(map(str, mask)) + '},')
parts += ['};', 'const lv_image_dsc_t dsr_symbol_atlas[%d] = {' % COUNT]
for i in range(COUNT):
    parts.append('{.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.w=64,.h=64,.stride=64},.data_size=4096,.data=masks[%d]},' % i)
parts += ['};', '']
(ROOT / 'components/dsr_ui/dsr_ui_icons.c').write_text('\n'.join(parts))
print('Generated %d filtered A8 Material Symbols Rounded masks (%d bytes).' % (COUNT, COUNT * 4096))
